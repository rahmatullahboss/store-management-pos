import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const lifecyclePath = "docs/architecture/staging/internal-token-key-lifecycle.md";
if (!existsSync(lifecyclePath)) {
  throw new Error("asymmetric key lifecycle document was not generated by the full suite");
}
const source = readFileSync(lifecyclePath, "utf8");
const lines = source.split("\n");
const indexes = lines
  .map((line, index) => /[ \t]+$/u.test(line) ? index : -1)
  .filter((index) => index >= 0);
if (indexes.length > 1) {
  throw new Error(`expected at most one lifecycle whitespace line, found ${indexes.length}`);
}
if (indexes.length === 1) {
  lines[indexes[0]] = lines[indexes[0]].replace(/[ \t]+$/u, "");
  writeFileSync(lifecyclePath, lines.join("\n"));
}

const basePackage = execFileSync(
  "git",
  ["show", "6be2f1fdde595c2f4fa8080cac68b7932d042ada:package.json"],
  { encoding: "utf8" },
);
writeFileSync("package.json", basePackage);
unlinkSync("tooling/scripts/preverify-asymmetric-checkpoint-cleanup.mjs");
unlinkSync(fileURLToPath(import.meta.url));
